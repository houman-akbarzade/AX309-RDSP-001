#!/usr/bin/env python3
"""Generate Verilog coefficient ROMs from the frozen C02 JSON contract."""
from pathlib import Path
import hashlib
import json

ROOT = Path(__file__).resolve().parents[2]
CONTRACT = ROOT / "engineering/S04-C02-SELECTED-C-EXECUTABLE-ARITHMETIC-CONTRACT-v1.0.json"
OUT_MF = ROOT / "rtl/mf16/mf16_coeff_rom.v"
OUT_TW = ROOT / "rtl/fft32/fft32_twiddle_rom.v"

raw = CONTRACT.read_bytes()
contract = json.loads(raw)
mf = contract["MF"]["mf16_stored_pairs"]
stages = contract["FFT"]["stages"]
assert len(mf) == 16
assert [s["stage"] for s in stages] == [1, 2, 3, 4, 5]
assert [s["shift"] for s in stages] == [0, 1, 0, 1, 1]

mf_lines = [
    "// Generated by rtl/tools/generate_numeric_roms.py.",
    "// Source: frozen C02 executable contract; do not edit by hand.",
    "// C02 SHA-256: " + hashlib.sha256(raw).hexdigest(),
    "module mf16_coeff_rom(input wire [3:0] index,",
    "    output reg signed [15:0] coeff_re,",
    "    output reg signed [15:0] coeff_im);",
    "always @* begin",
    "    coeff_re = 16'sd0; coeff_im = 16'sd0;",
    "    case (index)",
]
def lit(v):
    return ("-16'sd%d" % abs(v)) if v < 0 else ("16'sd%d" % v)

for i, (re, im) in enumerate(mf):
    mf_lines.append("      4'd%d: begin coeff_re=%s; coeff_im=%s; end" % (i, lit(re), lit(im)))
mf_lines += ["      default: begin coeff_re=16'sd0; coeff_im=16'sd0; end",
             "    endcase", "end", "endmodule", ""]
OUT_MF.write_text("\n".join(mf_lines), encoding="ascii")

tw_lines = [
    "// Generated by rtl/tools/generate_numeric_roms.py.",
    "// Source: frozen C02 executable contract; forward FFT, negative exponent.",
    "// C02 SHA-256: " + hashlib.sha256(raw).hexdigest(),
    "module fft32_twiddle_rom(input wire [2:0] stage,",
    "    input wire [3:0] index,",
    "    output reg signed [15:0] tw_re,",
    "    output reg signed [15:0] tw_im);",
    "always @* begin",
    "    tw_re=16'sd0; tw_im=16'sd0;",
    "    case ({stage,index})",
]
for s in stages:
    for i, (re, im) in enumerate(s["twiddle_stage_stored_pairs"]):
        tw_lines.append("      7'd%d: begin tw_re=%s; tw_im=%s; end" %
                        ((s["stage"] << 4) | i, lit(re), lit(im)))
tw_lines += ["      default: begin tw_re=16'sd0; tw_im=16'sd0; end",
             "    endcase", "end", "endmodule", ""]
OUT_TW.write_text("\n".join(tw_lines), encoding="ascii")
print("C02_SHA256", hashlib.sha256(raw).hexdigest())
print("MF_ROM", OUT_MF.relative_to(ROOT), len(mf), "entries")
print("TWIDDLE_ROM", OUT_TW.relative_to(ROOT), sum(len(s["twiddle_stage_stored_pairs"]) for s in stages), "entries")
